// Import AWS Lambda HTTP API Gateway v2 event and result TypeScript definitions
import { APIGatewayProxyEventV2, APIGatewayProxyResultV2 } from 'aws-lambda'; // Lambda event and response types

// Import DynamoDB Commands for retrieving, updating, and writing items atomically
import { GetCommand, PutCommand, UpdateCommand } from '@aws-sdk/lib-dynamodb'; // DynamoDB document client commands

// Import SNS Client and Publish Command for broadcasting vehicle replacement alerts
import { SNSClient, PublishCommand } from '@aws-sdk/client-sns'; // AWS SDK v3 SNS client

// Import document client instance, table name, and weight estimator from shared DB module
import { docClient, TABLE_NAME, getEstimatedWeightKg } from '../../shared/db'; // Shared DB utilities

// Import cryptographic signature verification and payload decoding from shared crypto module
import { verifySignature, fromBase64Url, isTokenValidTimestamp } from '../../shared/crypto'; // Crypto functions

// Import domain interfaces from shared types module
import { BayTokenPayload, ScanRequestBody, ScanResponse, BinGoCardProgress, HouseholdRecord, VehicleRecord } from '../../shared/types'; // Types

// Read HMAC secret key from Lambda environment variables with dev fallback
const BAY_SECRET = process.env.BAY_SECRET || 'bingo-dev-super-secret-key-32ch'; // Secret key for validating tokens

// Read SNS Topic ARN from Lambda environment variables for vehicle swap alerts
const SNS_TOPIC_ARN = process.env.SNS_TOPIC_ARN || ''; // Target SNS topic ARN for alerts

// Instantiate SNS client configured for the regional AWS environment
const snsClient = new SNSClient({ region: process.env.AWS_REGION || 'ap-south-1' }); // SNS client targeting Mumbai

// Construct structured HTTP API response with JSON payload and CORS headers
function buildJsonResponse(statusCode: number, body: object): APIGatewayProxyResultV2 { // Standard HTTP response helper
  return { // Return response object conforming to APIGatewayProxyResultV2
    statusCode, // HTTP status code
    headers: { // Standard response headers
      'Content-Type': 'application/json', // Content type header
      'Access-Control-Allow-Origin': '*', // Allow cross-origin requests from web and mobile apps
      'Access-Control-Allow-Methods': 'POST, OPTIONS', // Allowed HTTP verbs
      'Access-Control-Allow-Headers': 'Content-Type, Authorization', // Allowed request headers
    }, // End of headers
    body: JSON.stringify(body), // Serialize payload to JSON string
  }; // End of response object
} // End of buildJsonResponse helper

// Main AWS Lambda handler function for processing resident QR code scans
export const handler = async (event: APIGatewayProxyEventV2): Promise<APIGatewayProxyResultV2> => { // Lambda handler
  try { // Wrap execution in a try-catch block for clean error responses
    // Validate that request contains a non-empty body
    if (!event.body) { // Check if HTTP request body is absent
      return buildJsonResponse(400, { error: 'EmptyBody', message: 'Request body cannot be empty' }); // Return 400
    } // End of body existence check

    // Parse incoming JSON body into ScanRequestBody structure
    const body: ScanRequestBody = typeof event.body === 'string' ? JSON.parse(event.body) : event.body; // Parse JSON
    const { qrData, signature, householdId } = body; // Destructure required request fields

    // Validate presence of all mandatory parameters
    if (!qrData || !signature || !householdId) { // Check for missing parameters
      return buildJsonResponse(400, { // Return 400 Bad Request
        error: 'MissingParameters', // Error identifier
        message: 'qrData, signature, and householdId are required fields', // Explanatory message
      }); // End of return
    } // End of parameter validation

    // Step 1: Verify HMAC-SHA256 signature to guarantee QR was generated by an authentic bay tablet
    const isValidSignature = verifySignature(qrData, signature, BAY_SECRET); // Perform constant-time signature check
    if (!isValidSignature) { // Check if signature verification failed
      return buildJsonResponse(401, { // Return 401 Unauthorized
        error: 'InvalidSignature', // Error identifier
        message: 'QR code signature is invalid. Ensure you are scanning an authentic vehicle display.', // Explanation
      }); // End of return
    } // End of signature check

    // Step 2: Decode the Base64URL payload to inspect token contents
    const token: BayTokenPayload = fromBase64Url<BayTokenPayload>(qrData); // Decode Base64URL string into typed token

    // Step 3: Validate that the token timestamp has not expired (60s lifetime with 10s skew allowance)
    if (!isTokenValidTimestamp(token.exp, 10)) { // Check if current time exceeds expiration threshold
      return buildJsonResponse(400, { // Return 400 Bad Request
        error: 'TokenExpired', // Error identifier
        message: 'This QR code has expired. Please scan the current code refreshed on the vehicle bay display.', // Message
      }); // End of return
    } // End of expiration check

    // Step 4: Replay prevention - check if token nonce has already been consumed
    const nowTimestamp = new Date().toISOString(); // Current timestamp in ISO 8601 format
    const nowEpochSeconds = Math.floor(Date.now() / 1000); // Current timestamp in Unix epoch seconds
    const noncePk = `TOKEN#${token.nonce}`; // Construct partition key for nonce item
    try { // Attempt atomic nonce registration in DynamoDB
      await docClient.send(new PutCommand({ // Send PutCommand to register nonce
        TableName: TABLE_NAME, // Target DynamoDB table
        Item: { // Record attributes
          PK: noncePk, // Primary partition key
          SK: 'NONCE', // Primary sort key
          householdId, // Record which household used this token
          bayId: token.bayId, // Record bay where token was redeemed
          usedAt: nowTimestamp, // Timestamp when token was redeemed
          ttl: token.exp + 120, // Expire record automatically after 2 minutes via DynamoDB TTL
        }, // End of Item
        ConditionExpression: 'attribute_not_exists(PK)', // Reject if nonce already exists in table
      })); // End of docClient.send
    } catch (nonceError: any) { // Catch conditional check failure
      if (nonceError.name === 'ConditionalCheckFailedException') { // Detect duplicate nonce error
        return buildJsonResponse(409, { // Return 409 Conflict
          error: 'ReplayDetected', // Error identifier
          message: 'This QR token has already been scanned and processed. Each code can only be used once.', // Explanation
        }); // End of return
      } // End of condition check detection
      throw nonceError; // Re-throw any other database exception
    } // End of nonce verification block

    // Step 5: Retrieve or initialize Household profile to update BinGo card progress
    const householdPk = `HOUSEHOLD#${householdId}`; // Construct partition key for household
    const householdRes = await docClient.send(new GetCommand({ // Query household record
      TableName: TABLE_NAME, // Target table
      Key: { PK: householdPk, SK: 'PROFILE' }, // Primary key coordinates
    })); // End of GetCommand send

    // Initialize default card progress if household is new, otherwise load existing progress
    let existingProfile: HouseholdRecord | undefined = householdRes.Item as HouseholdRecord | undefined; // Cast item
    let currentCard: BinGoCardProgress = existingProfile?.cardProgress || { // Load or create card progress
      wet: false, // Default wet waste status
      sanitary: false, // Default sanitary waste status
      dry: false, // Default dry waste status
      furniture: false, // Default furniture waste status
      event: false, // Default event waste status
    }; // End of card progress initialization

    // Mark the scanned waste category square as completed
    currentCard[token.wasteType] = true; // Set current waste stream flag to true

    // Check if all 5 squares are filled to trigger a BinGo achievement
    const bingoWon = currentCard.wet && currentCard.sanitary && currentCard.dry && currentCard.furniture && currentCard.event; // Check BinGo
    const newStreak = (existingProfile?.streakDays || 0) + 1; // Increment resident streak count
    const todayDate = nowTimestamp.split('T')[0]; // Extract YYYY-MM-DD date string

    // Update household profile record in DynamoDB with new card status and activity date
    await docClient.send(new UpdateCommand({ // Send UpdateCommand
      TableName: TABLE_NAME, // Target table
      Key: { PK: householdPk, SK: 'PROFILE' }, // Household primary key coordinates
      UpdateExpression: 'SET cardProgress = :cp, lastActiveDate = :lad, streakDays = :sd, isOutOfStation = :oos, GSI1PK = :gpk, GSI1SK = :gsk', // Update expression
      ExpressionAttributeValues: { // Expression attribute values mapping
        ':cp': currentCard, // Updated BinGo card progress object
        ':lad': todayDate, // Updated last active date
        ':sd': newStreak, // Updated streak days count
        ':oos': false, // Automatically clear out-of-station flag since resident is actively disposing waste
        ':gpk': `ZONE#${token.zoneId}`, // GSI1 partition key pointing to zone
        ':gsk': householdPk, // GSI1 sort key pointing to household ID
      }, // End of attribute values
    })); // End of UpdateCommand send

    // Step 6: Log scan transaction item for auditing, history, and dashboard metrics
    const scanId = `scn_${token.nonce}`; // Generate deterministic scan ID tied to nonce
    const depositWeightKg = getEstimatedWeightKg(token.wasteType); // Calculate estimated weight for waste type
    await docClient.send(new PutCommand({ // Send PutCommand to store scan record
      TableName: TABLE_NAME, // Target table
      Item: { // Record attributes
        PK: householdPk, // Partition key grouped by household
        SK: `SCAN#${nowTimestamp}#${scanId}`, // Sort key timestamped for chronological sorting
        GSI1PK: `ZONE#${token.zoneId}`, // GSI1 partition key for querying all zone scans
        GSI1SK: `SCAN#${nowTimestamp}`, // GSI1 sort key for chronological zone activity feed
        scanId, // Unique scan identifier
        householdId, // Associated household ID
        zoneId: token.zoneId, // Associated zone ID
        bayId: token.bayId, // Scanned vehicle bay ID
        wasteType: token.wasteType, // Waste stream type
        weightKg: depositWeightKg, // Estimated deposit weight in kg
        timestamp: nowTimestamp, // ISO timestamp of deposit
        bingoAwarded: bingoWon, // Flag whether this scan unlocked BinGo completion
      }, // End of Item
    })); // End of PutCommand send

    // Step 7: Update vehicle load counter and evaluate if 75% swap alert threshold is reached
    const vehiclePk = `ZONE#${token.zoneId}`; // Partition key for zone vehicles
    const vehicleSk = `VEHICLE#${token.wasteType}`; // Sort key for specific waste type vehicle
    const vehicleRes = await docClient.send(new GetCommand({ // Query current vehicle state
      TableName: TABLE_NAME, // Target table
      Key: { PK: vehiclePk, SK: vehicleSk }, // Vehicle primary key coordinates
    })); // End of GetCommand send

    // Read current vehicle load and capacity or use sensible defaults (1000 kg capacity)
    const existingVehicle: VehicleRecord | undefined = vehicleRes.Item as VehicleRecord | undefined; // Cast vehicle
    const vehicleCapacityKg = existingVehicle?.capacityKg || 1000; // Vehicle capacity in kg
    const previousLoadKg = existingVehicle?.currentLoadKg || 0; // Prior load in kg
    const newLoadKg = previousLoadKg + depositWeightKg; // Compute updated load with new deposit
    const newFillPercentage = Math.min(100, Math.round((newLoadKg / vehicleCapacityKg) * 1000) / 10); // Compute percentage to 1 decimal

    // Flag whether vehicle crossed the 75% capacity threshold on this deposit
    const crossedThreshold = newFillPercentage >= 75 && (existingVehicle?.fillPercentage || 0) < 75; // Detect threshold crossing
    let swapAlertTriggered = false; // Initialize swap alert dispatched status flag

    // Update vehicle record in DynamoDB with new load and fill percentage
    await docClient.send(new UpdateCommand({ // Send UpdateCommand for vehicle state
      TableName: TABLE_NAME, // Target table
      Key: { PK: vehiclePk, SK: vehicleSk }, // Vehicle primary key coordinates
      UpdateExpression: 'SET currentLoadKg = :load, fillPercentage = :fill, lastActiveTimestamp = :ts, #status = :st', // Update fields
      ExpressionAttributeNames: { '#status': 'status' }, // Alias reserved keyword status
      ExpressionAttributeValues: { // Expression values
        ':load': newLoadKg, // Updated load in kg
        ':fill': newFillPercentage, // Updated fill percentage
        ':ts': nowTimestamp, // Timestamp of last deposit
        ':st': crossedThreshold ? 'swapping' : (existingVehicle?.status || 'active'), // Set status to swapping if threshold reached
      }, // End of attribute values
    })); // End of UpdateCommand send

    // Step 8: Trigger Amazon SNS vehicle replacement swap alert if threshold was crossed
    if (crossedThreshold && SNS_TOPIC_ARN) { // Check if threshold was met and SNS topic is configured
      try { // Attempt publishing notification to SNS
        const alertMessage = JSON.stringify({ // Construct SNS alert notification payload
          alert: 'VEHICLE_SWAP_REQUIRED', // Alert type identifier
          zoneId: token.zoneId, // Affected municipal zone
          wasteType: token.wasteType, // Waste stream requiring vehicle replacement
          bayId: token.bayId, // Bay identifier
          currentLoadKg: newLoadKg, // Current accumulated weight in kg
          capacityKg: vehicleCapacityKg, // Total vehicle capacity in kg
          fillPercentage: newFillPercentage, // Fill level percentage
          simulated: true, // Clearly mark simulated telemetry per hackathon guidelines
          timestamp: nowTimestamp, // Timestamp alert was emitted
        }); // End of alertMessage serialization

        // Publish swap alert message to Amazon SNS
        await snsClient.send(new PublishCommand({ // Send PublishCommand
          TopicArn: SNS_TOPIC_ARN, // Destination SNS Topic ARN
          Subject: `[BinGo Alert] ${token.wasteType.toUpperCase()} Vehicle at ${token.zoneId} reached ${newFillPercentage}%`, // Alert subject line
          Message: alertMessage, // Serialized JSON alert message body
        })); // End of snsClient.send

        swapAlertTriggered = true; // Mark alert as successfully triggered

        // Log active swap alert item in DynamoDB for the government dashboard alerts list
        await docClient.send(new PutCommand({ // Store alert item in DynamoDB
          TableName: TABLE_NAME, // Target table
          Item: { // Record attributes
            PK: `ZONE#${token.zoneId}`, // Partition key
            SK: `ALERT#${nowTimestamp}#${token.wasteType}`, // Sort key
            GSI1PK: 'ALERT#STATUS', // GSI1 partition key for querying open alerts
            GSI1SK: `ACTIVE#${nowTimestamp}`, // GSI1 sort key for active alerts
            zoneId: token.zoneId, // Municipal zone
            wasteType: token.wasteType, // Waste category
            vehicleId: existingVehicle?.vehicleId || `VH-${token.wasteType.toUpperCase()}-01`, // Vehicle registration ID
            fillPercentage: newFillPercentage, // Recorded fill percentage
            status: 'PENDING', // Operational status of replacement dispatch
            simulated: true, // Transparent simulation indicator
            createdAt: nowTimestamp, // Creation timestamp
          }, // End of Item
        })); // End of PutCommand send
      } catch (snsError) { // Catch SNS publication failure
        console.error('Failed to publish vehicle swap alert to SNS:', snsError); // Log error but do not fail resident scan
      } // End of catch block
    } // End of threshold alert check

    // Step 9: Construct and return successful ScanResponse payload
    const responsePayload: ScanResponse = { // Assemble response object conforming to ScanResponse
      success: true, // Successful operation flag
      scanId, // Scan transaction ID
      timestamp: nowTimestamp, // Timestamp of confirmed deposit
      wasteType: token.wasteType, // Registered waste stream
      householdId, // Validated household ID
      cardProgress: currentCard, // Updated state of all 5 card squares
      bingoWon, // Flag indicating whether player completed full card
      vehicleFillPercentage: newFillPercentage, // Updated fill percentage of vehicle
      swapAlertTriggered, // Notification flag
      message: bingoWon // Dynamic congratulatory or confirmation message
        ? 'BinGo! You have segregated all 5 waste streams and completed your card!' // BinGo completion message
        : `Deposit confirmed for ${token.wasteType} waste. Green tick awarded!`, // Standard confirmation message
    }; // End of responsePayload

    // Return HTTP 200 with complete response details
    return buildJsonResponse(200, responsePayload); // Return HTTP 200 OK
  } catch (error: any) { // Catch any unhandled errors
    console.error('Error processing scan:', error); // Log unexpected error to CloudWatch
    return buildJsonResponse(500, { // Return HTTP 500 Internal Server Error
      error: 'ScanProcessingFailed', // Error classification
      message: error?.message || 'An error occurred while processing your waste scan', // Error message
    }); // End of 500 return
  } // End of outer catch block
}; // End of handler export
